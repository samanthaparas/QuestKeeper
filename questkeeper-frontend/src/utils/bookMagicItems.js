function slugify(text) {
  return text.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

const RARITY_ORDER = ["Common", "Uncommon", "Rare", "Very Rare", "Legendary", "Artifact"];

// Facts that can be read from just the name and type (the same rules the
// backend catalog uses). Anything that needs the description stays unknown.
const SLOTS = [
  ["Head", /\b(hat|helm|helmet|circlet|crown|cap|headband|diadem|tiara|hood)\b/i],
  ["Eyes", /\b(goggles|lenses|spectacles|eyes of|monocle)\b/i],
  ["Neck", /\b(amulet|necklace|periapt|medallion|scarab|torc|pendant|choker|locket)\b/i],
  ["Shoulders", /\b(cloak|cape|mantle)\b/i],
  ["Body", /\b(robe|vestments|shirt|coat|tunic|jacket|dress|gown)\b/i],
  ["Hands", /\b(gloves|gauntlets?|mittens)\b/i],
  ["Wrists", /\b(bracers|bracelets?|armbands?)\b/i],
  ["Waist", /\b(belt|girdle|sash)\b/i],
  ["Feet", /\b(boots|slippers|sandals|shoes)\b/i],
];

function slotFor(name, type) {
  if (/\bshield\b/i.test(name) && type !== "Weapon") return "Shield";
  if (type === "Ring") return "Ring";
  if (type === "Armor") return "Armor";
  if (type !== "Wondrous Item") return null;
  return SLOTS.find(([, pattern]) => pattern.test(name))?.[0] ?? null;
}

// The same shape as the catalog entries from the backend, so the Magic Items
// page can filter both together. Facts that come from reading an item's
// description (worn where, consumable, useful for, who can attune) aren't
// known for book items, so they're left empty.
export const BOOK_MAGIC_ITEMS = ROWS.map(([name, type, rarity, attuned, book, page], position) => ({
  index: `book_mi_${slugify(name)}_${position}`,
  name,
  source: BOOKS[book],
  sourceGroup: OFFICIAL_BOOKS_GROUP,
  edition: "2014",
  is_book_entry: true,
  book: BOOKS[book],
  type: slotFor(name, type) === "Shield" ? "Shield" : type,
  kinds: [],
  rarities: [rarity],
  rarity,
  rarityRank: RARITY_ORDER.includes(rarity) ? RARITY_ORDER.indexOf(rarity) : 99,
  attunement: Boolean(attuned),
  attunementLimits: { classes: [], races: [], alignments: [], spellcaster: false, text: null },
  wornSlot: slotFor(name, type),
  shield: slotFor(name, type) === "Shield",
  // Potions and scrolls are always used up; other items are unknown (null).
  consumable: type === "Potion" || type === "Scroll" ? true : null,
  usefulFor: [],
  versions: [],
  link_url: `${WIKIDOT}${page}`,
}));
